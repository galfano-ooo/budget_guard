# -*- coding: utf-8 -*-
"""
BudgetGuard installer: links a UE project to this repo (repo-linked, nothing is copied).

Writes/updates <UEProject>/Content/Python/init_unreal.py with a delimited block that appends
this repo's folder to sys.path and registers Tools -> BudgetGuard (inside a try/except, so a
missing PySide6 never breaks the Editor start). Re-running replaces only that block in place
(e.g. after moving the repo), leaving the rest of the file untouched. Updating the tool =
`git pull` / replace the repo folder; no re-install needed.

Also: enables PythonScriptPlugin in the .uproject (a .bak is written first), and pip-installs
PySide6 with UE's OWN interpreter into <Project>/Content/Python/Lib/site-packages (skipped when
already importable there). The engine is found from the .uproject's EngineAssociation; pass
--engine when that lookup fails.

Run from anywhere:
    python installer/install_ue_project.py "D:/MyGame"
    python installer/install_ue_project.py "D:/MyGame" --dry-run
    python installer/install_ue_project.py "D:/MyGame" --engine "D:/UE_5.7"
    python installer/install_ue_project.py "D:/MyGame" --no-pyside
    python installer/install_ue_project.py "D:/MyGame" --uninstall   # remove the managed block
"""
import argparse
import glob
import json
import os
import shutil
import subprocess

MARKER_BEGIN = "# >>> BudgetGuard managed block - do not edit by hand >>>"
MARKER_END = "# <<< BudgetGuard managed block <<<"

REPO_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIR = os.path.join(REPO_DIR, "src")   # the sys.path entry: audit_*.py + budgetguard_ui/

PYSIDE6_SPEC = "PySide6==6.11.2"   # same version greybox_gen proved live
UE_PYTHON_REL = os.path.join("Binaries", "ThirdParty", "Python3", "Win64", "python.exe")
LAUNCHER_INSTALLED_DAT = os.path.join(os.environ.get("PROGRAMDATA", r"C:\ProgramData"),
                                      "Epic", "UnrealEngineLauncher", "LauncherInstalled.dat")
DEFAULT_LAUNCHER_ROOT = os.path.join(os.environ.get("PROGRAMFILES", r"C:\Program Files"),
                                     "Epic Games")
MAX_PARENT_HOPS = 3


def build_block(repo_dir):
    return "\n".join([
        MARKER_BEGIN,
        "# Auto-generated by installer/install_ue_project.py - re-run it to update this block",
        "# (e.g. after moving the repo) instead of hand-editing it.",
        "import sys as _budgetguard_sys",
        "_BUDGETGUARD_DIR = {!r}".format(repo_dir),
        "if _BUDGETGUARD_DIR not in _budgetguard_sys.path:",
        "    _budgetguard_sys.path.append(_BUDGETGUARD_DIR)",
        "# Tools -> BudgetGuard. Never allowed to break the rest of init_unreal.py.",
        "try:",
        "    import budgetguard_ui",
        "    budgetguard_ui.register_menu()",
        "except Exception as _budgetguard_exc:",
        "    import unreal as _budgetguard_unreal",
        "    _budgetguard_unreal.log_warning(",
        "        '[BudgetGuard] menu not registered: %r' % (_budgetguard_exc,))",
        MARKER_END,
    ]) + "\n"


def find_uproject(project_dir):
    try:
        entries = sorted(os.listdir(project_dir))
    except OSError:
        return None
    for entry in entries:
        if entry.lower().endswith(".uproject"):
            return entry
    return None


def resolve_project_dir(path, log=print):
    """The UE project root for `path`: the folder holding a .uproject, the folder of a
    .uproject file, else the nearest parent (up to MAX_PARENT_HOPS). SystemExit when none."""
    path = os.path.abspath(path.strip().strip('"'))
    if os.path.isfile(path):
        if path.lower().endswith(".uproject"):
            return os.path.dirname(path)
        raise SystemExit("Not a project folder or .uproject file: {}".format(path))
    if not os.path.isdir(path):
        raise SystemExit("Not a directory: {}".format(path))
    candidate = path
    for _ in range(MAX_PARENT_HOPS + 1):
        if find_uproject(candidate):
            if candidate != path:
                log("{} holds no .uproject - installing into its project root {} instead."
                    .format(path, candidate))
            return candidate
        parent = os.path.dirname(candidate)
        if parent == candidate:
            break
        candidate = parent
    raise SystemExit("No .uproject file in {} or its parent folders. Pick the UE project folder "
                     "(the one holding the .uproject file).".format(path))


def find_stray_installs(project_dir):
    """Managed init_unreal.py files below Content/ other than Content/Python/ - UE never runs them."""
    content = os.path.join(project_dir, "Content")
    stray = []
    for depth in ("*", os.path.join("*", "*")):
        for path in glob.glob(os.path.join(content, depth, "Python", "init_unreal.py")):
            try:
                with open(path, "r", encoding="utf-8") as f:
                    if MARKER_BEGIN in f.read():
                        stray.append(os.path.normpath(path))
            except OSError:
                pass
    return sorted(stray)


