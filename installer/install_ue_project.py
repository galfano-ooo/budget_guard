# .uproject: enable PythonScriptPlugin
# ---------------------------------------------------------------------------

def enable_python_plugin(project_dir, dry_run=False, log=print):
    uproject = find_uproject(project_dir)
    path = os.path.join(project_dir, uproject)
    try:
        with open(path, "r", encoding="utf-8-sig") as f:
            data = json.load(f)
    except (OSError, ValueError) as exc:
        log("WARNING: could not read {} ({}); enable 'Python Editor Script Plugin' by hand."
            .format(path, exc))
        return
    plugins = data.setdefault("Plugins", [])
    existing = next((p for p in plugins if p.get("Name") == "PythonScriptPlugin"), None)
    if existing and existing.get("Enabled") is True:
        log("PythonScriptPlugin already enabled.")
        return
    if dry_run:
        log("[dry-run] would enable PythonScriptPlugin in {}".format(path))
        return
    shutil.copy2(path, path + ".bak")
    if existing:
        existing["Enabled"] = True
    else:
        plugins.append({"Name": "PythonScriptPlugin", "Enabled": True})
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent="\t")
    log("PythonScriptPlugin enabled in {} (backup: .bak). Restart the Editor.".format(path))


