def _read_engine_association(project_dir):
    uproject = find_uproject(project_dir)
    if not uproject:
        return None
    try:
        with open(os.path.join(project_dir, uproject), "r", encoding="utf-8-sig") as f:
            return (json.load(f).get("EngineAssociation") or "").strip() or None
    except (OSError, ValueError):
        return None


def _registry_engine_dir(association):
    try:
        import winreg
    except ImportError:
        return None
    try:
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER,
                            r"Software\Epic Games\Unreal Engine\Builds") as key:
            return winreg.QueryValueEx(key, association)[0]
    except OSError:
        pass
    try:
        with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE,
                            "SOFTWARE\\EpicGames\\Unreal Engine\\" + association) as key:
            return winreg.QueryValueEx(key, "InstalledDirectory")[0]
    except OSError:
        return None


def _launcher_engine_dir(association, dat_path=None):
    app = "UE_" + association
    try:
        with open(dat_path or LAUNCHER_INSTALLED_DAT, "r", encoding="utf-8") as f:
            for item in json.load(f).get("InstallationList", []):
                if item.get("AppName") == app and item.get("InstallLocation"):
                    return item["InstallLocation"]
    except (OSError, ValueError, AttributeError):
        pass
    default = os.path.join(DEFAULT_LAUNCHER_ROOT, app)
    return default if os.path.isdir(default) else None


def find_ue_python(project_dir, engine_dir=None):
    """(python_exe or None, how it was found / why not)."""
    how = "--engine"
    if not engine_dir:
        association = _read_engine_association(project_dir)
        if not association:
            return None, "no EngineAssociation in the .uproject"
        engine_dir = _registry_engine_dir(association) or _launcher_engine_dir(association)
        if not engine_dir:
            return None, ("EngineAssociation {} not found in the registry or the Epic "
                          "launcher's install list".format(association))
        how = "EngineAssociation {}".format(association)
    for candidate in (os.path.join(engine_dir, "Engine", UE_PYTHON_REL),
                      os.path.join(engine_dir, UE_PYTHON_REL)):
        if os.path.isfile(candidate):
            return os.path.normpath(candidate), how
    return None, "no {} under {}".format(UE_PYTHON_REL, engine_dir)


def site_packages_dir(project_dir):
    # UE puts <Project>/Content/Python/Lib/site-packages on sys.path by itself
    return os.path.join(project_dir, "Content", "Python", "Lib", "site-packages")


def pyside6_version(ue_python, site_dir):
    code = ("import sys; sys.path.insert(0, {!r}); import PySide6; "
            "print(PySide6.__version__)").format(site_dir)
    try:
        proc = subprocess.run([ue_python, "-c", code], capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.TimeoutExpired):
        return None
    out = proc.stdout.strip()
    return out if proc.returncode == 0 and out else None


def install_pyside6(project_dir, engine_dir=None, dry_run=False, log=print):
    """pip-install PYSIDE6_SPEC into the project with UE's own Python. Never raises."""
    ue_python, how = find_ue_python(project_dir, engine_dir)
    if not ue_python:
        log("PySide6 step skipped: could not find UE's Python ({}). Re-run with --engine "
            "\"<engine root>\" (GUI: Engine folder).".format(how))
        return False
    site_dir = site_packages_dir(project_dir)
    log("UE Python: {}  (via {})".format(ue_python, how))
    present = pyside6_version(ue_python, site_dir)
    if present:
        log("PySide6 {} already importable from {} - pip step skipped.".format(present, site_dir))
        return True
    cmd = [ue_python, "-m", "pip", "install", PYSIDE6_SPEC, "--target", site_dir]
    printable = subprocess.list2cmdline(cmd)
    if dry_run:
        log("[dry-run] would run: " + printable)
        return True
    log("Installing {} (~250 MB download, takes a few minutes):".format(PYSIDE6_SPEC))
    log("  " + printable)
    os.makedirs(site_dir, exist_ok=True)
    try:
        proc = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    except OSError as exc:
        log("ERROR: could not start pip: {}".format(exc))
        return False
    for line in proc.stdout:
        log("  pip: " + line.rstrip())
    if proc.wait() != 0:
        log("ERROR: pip exited {} - PySide6 not installed; the panel can't open yet."
            .format(proc.returncode))
        return False
    log("PySide6 installed into {}".format(site_dir))
    return True


# ---------------------------------------------------------------------------
# init_unreal.py block
# ---------------------------------------------------------------------------

def _write_block(project_dir, dry_run, log):
    python_dir = os.path.join(project_dir, "Content", "Python")
    init_path = os.path.join(python_dir, "init_unreal.py")
    block = build_block(SRC_DIR)

    existing = ""
    if os.path.isfile(init_path):
        with open(init_path, "r", encoding="utf-8") as f:
            existing = f.read()

    if MARKER_BEGIN in existing and MARKER_END in existing:
        start = existing.index(MARKER_BEGIN)
        end = existing.index(MARKER_END) + len(MARKER_END)
        new_content = existing[:start] + block.rstrip("\n") + existing[end:]
        action = "updated"
    elif existing.strip():
        sep = "\n" if existing.endswith("\n") else "\n\n"
        new_content = existing + sep + block
        action = "appended to"
    else:
        new_content = block
        action = "created"

    if dry_run:
        log("[dry-run] would have {} {}".format(action, init_path))
        log(block)
        return
    os.makedirs(python_dir, exist_ok=True)
    with open(init_path, "w", encoding="utf-8") as f:
        f.write(new_content)
    log("{} {}".format(action, init_path))
    log("Linked to {}".format(SRC_DIR))


def _warn_legacy_copy(project_dir, log):
    """A copy-model install leaves audit_*.py in Content/Python; being earlier on sys.path
    than the repo, those stale copies would shadow it."""
    python_dir = os.path.join(project_dir, "Content", "Python")
    legacy = sorted(os.path.basename(p) for p in glob.glob(os.path.join(python_dir, "audit_*.py")))
    if os.path.isfile(os.path.join(python_dir, "budgetguard_ui", "__init__.py")) or legacy:
        log("WARNING: an old copy-model install is still in {} ({} audit_*.py file(s), "
            "budgetguard_ui/ ...). Content/Python is searched BEFORE the repo, so those stale "
            "copies shadow the linked repo. Delete them by hand (with the Editor closed): "
            "audit_*.py, audit_budgets.json, profile_*.json, tag_existing_content.py, "
            "build_tier_collections.py, dashboard/, budgetguard_ui/, examples/, "
            "deploy_source.txt.".format(python_dir, len(legacy)))


def install(project_dir, dry_run=False, engine_dir=None, pyside=True, log=print):
    project_dir = resolve_project_dir(project_dir, log=log)
    log("UE project: {}".format(os.path.join(project_dir, find_uproject(project_dir))))
    for stray in find_stray_installs(project_dir):
        log("Warning: stray managed init_unreal.py at {} - UE never runs it. Delete that "
            "folder by hand, with the Editor closed.".format(stray))
    _warn_legacy_copy(project_dir, log)
    _write_block(project_dir, dry_run, log)
    enable_python_plugin(project_dir, dry_run, log)
    if pyside:
        install_pyside6(project_dir, engine_dir, dry_run=dry_run, log=log)
    if not dry_run:
        log("Done. Restart the Unreal Editor, then open Tools -> BudgetGuard "
            "(or: import budgetguard_ui; budgetguard_ui.show()).")


def uninstall(project_dir, dry_run=False, log=print):
    """Remove only the managed block from init_unreal.py (PySide6 and the plugin flag stay)."""
    project_dir = resolve_project_dir(project_dir, log=log)
    init_path = os.path.join(project_dir, "Content", "Python", "init_unreal.py")
    if not os.path.isfile(init_path):
        log("No init_unreal.py at {} - nothing to remove.".format(init_path))
        return
    with open(init_path, "r", encoding="utf-8") as f:
        existing = f.read()
    if MARKER_BEGIN not in existing or MARKER_END not in existing:
        log("No BudgetGuard managed block in {}.".format(init_path))
        return
    start = existing.index(MARKER_BEGIN)
    end = existing.index(MARKER_END) + len(MARKER_END)
    remaining = (existing[:start].rstrip("\n") + "\n" + existing[end:].lstrip("\n")).strip("\n")
    if dry_run:
        log("[dry-run] would remove the managed block from {}".format(init_path))
        return
    if remaining:
        with open(init_path, "w", encoding="utf-8") as f:
            f.write(remaining + "\n")
        log("Removed the managed block from {}".format(init_path))
    else:
        os.remove(init_path)
        log("Removed {} (it held only the managed block)".format(init_path))


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("project", nargs="?", help="UE project folder (holds the .uproject) or the .uproject itself")
    parser.add_argument("--dry-run", action="store_true", help="Print what would change without writing anything")
    parser.add_argument("--engine", help="Engine root folder (the one holding Engine/), when the lookup fails")
    parser.add_argument("--no-pyside", action="store_true", help="Skip the PySide6 pip step")
    parser.add_argument("--uninstall", action="store_true", help="Remove the managed init_unreal.py block")
    args = parser.parse_args()

    project_dir = args.project or input("Path to the UE project folder: ").strip().strip('"')
    if not project_dir:
        raise SystemExit("No project path given.")
    if args.uninstall:
        uninstall(project_dir, dry_run=args.dry_run)
    else:
        install(project_dir, dry_run=args.dry_run, engine_dir=args.engine, pyside=not args.no_pyside)


if __name__ == "__main__":
    main()
